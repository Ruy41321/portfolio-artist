#!/usr/bin/env bash
# Creates the production .env with random secrets.
#   ./scripts/setup.sh                       # interactive
#   SITE_URL=https://example.com APP_PORT=3000 ./scripts/setup.sh   # non-interactive
set -euo pipefail
cd "$(dirname "$0")/.."

if [[ -f .env && "${FORCE:-}" != "1" ]]; then
  echo ".env already exists: nothing to do (use FORCE=1 to overwrite it)."
  exit 0
fi

random() { head -c 48 /dev/urandom | od -An -tx1 | tr -d ' \n' | head -c "$1"; }

SITE_URL=${SITE_URL:-}
if [[ -z "$SITE_URL" ]]; then
  read -r -p "Public address of the site (e.g. https://www.example.com): " SITE_URL
fi
SITE_URL=${SITE_URL%/}
if [[ ! "$SITE_URL" =~ ^https?://[^/]+$ ]]; then
  echo "Invalid address: use the form https://www.example.com" >&2
  exit 1
fi

APP_PORT=${APP_PORT:-}
if [[ -z "$APP_PORT" ]]; then
  read -r -p "Local port for the app, used by your reverse proxy [3000]: " APP_PORT
fi
APP_PORT=${APP_PORT:-3000}

cat > .env <<ENV
# Generated by scripts/setup.sh on $(date -u +%Y-%m-%d). See .env.example for all options.
NEXT_PUBLIC_SERVER_URL=$SITE_URL
PAYLOAD_SECRET=$(random 64)

POSTGRES_USER=portfolio
POSTGRES_PASSWORD=$(random 32)
POSTGRES_DB=portfolio

APP_PORT=$APP_PORT
APP_BIND=127.0.0.1
MAX_UPLOAD_MB=20

BACKUP_INTERVAL_HOURS=24
BACKUP_RETENTION_DAYS=14

# Optional email for the contact form (see .env.example)
# SMTP_HOST=
ENV
chmod 600 .env
echo "Created .env for $SITE_URL (app on 127.0.0.1:$APP_PORT)."
echo "Next: docker compose -f compose.prod.yml up -d"
